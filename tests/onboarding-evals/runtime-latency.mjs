// One synthetic introduction through the deployed public API. Never creates an account.
import assert from "node:assert/strict";
if (process.env.VERCEL_ENV !== "preview" || process.env.SORP_LIVE_EVAL !== "true") throw Error("Preview verification opt-in required");
const base = process.env.SORP_RUNTIME_URL || "https://sorp2026.org";
const target = new URL(base);
assert.ok(target.protocol === "https:" && (target.hostname === "sorp2026.org" || target.hostname.endsWith(".vercel.app")));
const headers = { "content-type": "application/json", origin: base, "sec-fetch-site": "same-origin" };
const started = await fetch(`${base}/api/onboarding/start/`, { method: "POST", headers, body: JSON.stringify({ attribution: { utm_source: "onboarding-speed-verification" } }) });
assert.equal(started.status, 200, "Onboarding session must start");
const cookie = started.headers.get("set-cookie")?.split(";")[0];
assert.ok(cookie?.startsWith("sorp_onboarding="));
headers.cookie = cookie;
const session = await fetch(`${base}/api/onboarding/session/`, { headers });
assert.equal(session.status, 200);
const saved = await session.json();
const begin = performance.now();
const response = await fetch(`${base}/api/onboarding/turn/`, { method: "POST", headers, body: JSON.stringify({ message: "I’m Sarah Speedcheck, an accountant at Example Advisory. My email is sarah.speedcheck@example.invalid.", fields: {}, revision: saved.state.revision }) });
const result = await response.json();
const durationMs = Math.round(performance.now() - begin);
assert.equal(response.status, 200, "Real onboarding turn must succeed");
assert.equal(result.notice || "", "", "A fallback is not a successful AI response");
assert.ok(!result.state.response?.generated, "A clear introduction should not wait for AI");
assert.equal(result.state.facts.email, "sarah.speedcheck@example.invalid");
assert.equal(result.state.facts.organisation, "Example Advisory");
const followUpStarted = performance.now();
const followUpResponse = await fetch(`${base}/api/onboarding/turn/`, { method: "POST", headers, body: JSON.stringify({ message: "I work with several charities, including Brainstrust and Oxfam, and I’m trying to improve how we gather impact evidence.", fields: {}, revision: result.state.revision }) });
const followUp = await followUpResponse.json();
const aiFollowUpMs = Math.round(performance.now() - followUpStarted);
assert.equal(followUpResponse.status, 200);
assert.equal(followUp.notice || "", "", "The contextual follow-up must use the real AI service");
assert.equal(followUp.state.response?.generated, true);
assert.equal(followUp.state.charity.confirmed, null);
const refreshed = await fetch(`${base}/api/onboarding/session/`, { headers });
const persisted = await refreshed.json();
assert.equal(persisted.state.facts.email, result.state.facts.email);
assert.equal(persisted.messages.at(-1).text, followUp.question);
console.log("ONBOARDING_RUNTIME_LATENCY " + JSON.stringify({ target: target.hostname, passed: true, firstReplyMs: durationMs, aiFollowUpMs, serverTiming: response.headers.get("server-timing"), genuineAIFollowUp: true, persistence: true, accountCreated: false, draftExpiry: "24 hours" }));
